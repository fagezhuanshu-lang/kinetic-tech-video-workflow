"""Generate an eight-second, license-clear pipeline fixture, not a spoken tutorial."""
from pathlib import Path
import argparse
import array
import json
import math
import struct
import sys
import wave
import zlib

def png(path):
    width, height = 360, 640
    scan = bytearray()
    for y in range(height):
        scan.append(0)
        for x in range(width):
            grid = x % 40 == 0 or y % 40 == 0
            rgb = (24, 45, 67) if grid else (12, 24, 40)
            if (x-180)**2 + (y-230)**2 < 72**2:
                rgb = (112, 187, 235)
            if 105 < y-230 < 295 and abs(x-180) < min(128, (y-260)*1.5):
                rgb = (64, 134, 190)
            if 150 < y < 180 and 35 < x < 92:
                rgb = (242, 200, 90)
            scan.extend(rgb)
    def chunk(name, body):
        return struct.pack('!I',len(body))+name+body+struct.pack('!I',zlib.crc32(name+body)&0xffffffff)
    path.write_bytes(b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('!2I5B',width,height,8,2,0,0,0))+chunk(b'IDAT',zlib.compress(bytes(scan),9))+chunk(b'IEND',b''))

def signal(path, kind, duration=8.1):
    rate = 48000
    values = array.array('h')
    for i in range(round(duration*rate)):
        t = i/rate
        if kind == 'test':
            phase = (t % .72)/.72
            gate = math.sin(math.pi*min(1,phase/.78))**2 if phase < .78 else 0
            freq = [227,251,283,239][int(t/.72)%4]
            value = .18*gate*(math.sin(2*math.pi*freq*t)+.25*math.sin(2*math.pi*2*freq*t))
        else:
            chord = [(110,138.59,164.81),(98,123.47,146.83)][int(t/2)%2]
            value = .07*sum(math.sin(2*math.pi*f*t) for f in chord)/3
            beat = (t % .5)
            value += .08*math.exp(-beat*22)*math.sin(2*math.pi*62*t)
        values.append(round(max(-1,min(1,value))*32767))
    if sys.byteorder != 'little':
        values.byteswap()
    with wave.open(str(path),'wb') as f:
        f.setparams((1,2,rate,len(values),'NONE','not compressed'))
        f.writeframes(values.tobytes())

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--out',type=Path,required=True)
    a=p.parse_args()
    out=a.out.resolve()
    if out.exists():
        p.error('Use a new output directory; existing demo is preserved.')
    out.mkdir(parents=True)
    png(out/'illustration.png')
    signal(out/'test-signal.wav','test')
    signal(out/'test-music.wav','music')
    user={
        'mode':'user-media','language':'zh','layout':'landscape','duration':8,
        'title':'流程验收样片','presenterLabel':'示例图形','content':{},
        'scenes':[{'id':'B1','title':'流程演示'}],
        'basic':{'label':'开源工作流','keyword':'把流程交给脚本','explanation':'动效、配乐与封面\n按同一份配置完成'},
        'media':{'presenter':{'mode':'image','file':'illustration.png','face':{'cx':.5,'cy':.36,'h':.23}},'voice':{'mode':'file','file':'test-signal.wav'},'music':{'mode':'none'}},
        'soundEffects':'native',
        'captions':[{'start':0,'end':2.4,'text':'这是流程验收样片'}, {'start':2.5,'end':5.1,'text':'当前声音是合成测试信号'}, {'start':5.2,'end':7.9,'text':'正式制作请换成自己的口播'}]
    }
    job={'version':1,'user_input':'user.json',
         'music':{'file':'test-music.wav','start':0,'name':'Generated test tones','source':'scripts/make_demo.py','license':'MIT; generated test fixture'},
         'cover':{'title':'把流程交给脚本','label':'开源工作流','subtitle':'动效、配乐与封面\n按同一份配置完成','footer':'动效 · 配乐 · 封面','frame':'illustration.png'}}
    for name,value in [('user.json',user),('job.json',job)]:
        (out/name).write_text(json.dumps(value,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    (out/'DEMO-NOTICE.txt').write_text('This fixture contains an original geometric illustration and mathematical test tones generated by make_demo.py. It contains no person, speech recording, downloaded music, or external factual claims. It tests execution, not editorial quality. Distributed under the repository MIT license.\n',encoding='utf-8')
    print(json.dumps({'job':str(out/'job.json'),'duration':8,'notice':'Synthetic test signals, not human speech'},ensure_ascii=False))

if __name__=='__main__':
    main()
